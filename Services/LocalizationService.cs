    public class LocalizationService : INotifyPropertyChanged
    {
        private static LocalizationService? _instance;
        public static LocalizationService Instance => _instance ??= new LocalizationService();

#if WINDOWS
        private readonly ResourceManager? _resourceManager;
        private ResourceContext? _resourceContext;
#endif
        private string _currentLanguage = "zh-CN";

        public event PropertyChangedEventHandler? PropertyChanged;
        public event EventHandler? LanguageChanged;

        public static Action<string>? LanguagePersister { get; set; }
        public static Func<string>? LanguageLoader { get; set; }

        private LocalizationService()
        {
#if WINDOWS
            try
            {
                _resourceManager = new ResourceManager();
                _resourceContext = _resourceManager.CreateResourceContext();
            }
            catch
            {
                _resourceManager = null;
                _resourceContext = null;
            }
#endif
            string savedLang = LanguageLoader?.Invoke() ?? "zh-CN";
            SetLanguage(savedLang);
        }

        public string CurrentLanguage
        {
            get => _currentLanguage;
            set
            {
                if (_currentLanguage != value)
                {
                    SetLanguage(value);
                }
            }
        }

        public void SetLanguage(string languageTag)
        {
            if (string.Equals(_currentLanguage, languageTag, StringComparison.OrdinalIgnoreCase)) return;
            _currentLanguage = languageTag;
            LanguagePersister?.Invoke(languageTag);

#if WINDOWS
            try
            {
                if (_resourceContext != null)
                {
                    _resourceContext.QualifierValues["Language"] = languageTag;
                }
            }
            catch
            {
                // 忽略系统未识别的语言标签异常，保留设置
            }
#endif

            PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(null));
            LanguageChanged?.Invoke(this, EventArgs.Empty);
        }

        /// <summary>
        /// 读取当前语言下的键值文本（优先使用内存高精度全量三语字典，保证语言切换即时生效）
        /// </summary>
        /// <param name="key">资源键名</param>
        /// <returns>本地化文本</returns>
        public string GetString(string key)
        {
            return GetString(key, null);
        }

        public string GetString(string key, string? fallback)
        {
            // 1. 优先从全量字典中精确匹配当前语言，彻底避免 Windows PRI Qualifier 缓存或系统默认语言拦截
            var fb = GetFallbackString(key, _currentLanguage);
            if (fb != key && !string.IsNullOrEmpty(fb))
            {
                return NormalizeNewlines(fb);
            }

#if WINDOWS
            // 2. 若字典未覆盖，回退到 Windows App SDK ResourceManager
            try
            {
                if (_resourceManager != null && _resourceContext != null)
                {
                    var candidate = _resourceManager.MainResourceMap.TryGetValue($"Resources/{key}", _resourceContext);
                    if (candidate != null && !string.IsNullOrEmpty(candidate.ValueAsString))
                    {
                        return NormalizeNewlines(candidate.ValueAsString);
                    }

                    candidate = _resourceManager.MainResourceMap.TryGetValue(key, _resourceContext);
                    if (candidate != null && !string.IsNullOrEmpty(candidate.ValueAsString))
                    {
                        return NormalizeNewlines(candidate.ValueAsString);
                    }
                }
            }
            catch
            {
                // 出错时使用 Fallback
            }
#endif

            var result = fb != key ? fb : (fallback ?? key);
            return NormalizeNewlines(result);
        }

        private static string NormalizeNewlines(string? text)
        {
            if (string.IsNullOrEmpty(text)) return text ?? string.Empty;
            return text.Replace("\\r\\n", "\n").Replace("\\n", "\n");
        }

